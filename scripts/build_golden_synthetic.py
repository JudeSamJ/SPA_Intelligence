"""Build eval/golden/<doc_id>/{doc.pdf, labels.json} for the synthetic smoke set from ground_truth.json.

The synthetic documents are generated by scripts/generate_samples.py, so their labels are known by construction.
They are a SMOKE SET: they prove the pipeline works, they say nothing about accuracy on real contracts.
Run:  python scripts/build_golden_synthetic.py
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from tests.fakes import oracle_input  # noqa: E402  (quotes/pages located in the real PDF text)

SCALARS = ["buyer", "unit_id", "price", "area_sqft", "handover_date", "grace_period_days", "delay_rate",
           "delay_basis", "delay_cap", "cancellation_clause"]


def main() -> None:
    truth = json.loads((ROOT / "ground_truth.json").read_text())
    for fname, t in truth.items():
        pdf = ROOT / "samples" / fname
        inp = oracle_input(pdf)
        doc_id = "synthetic_" + pdf.stem.replace("sample_", "")
        out = ROOT / "eval" / "golden" / doc_id
        out.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(pdf, out / "doc.pdf")
        labels = {"doc_id": doc_id, "kind": "synthetic", "synthetic": True, "currency": t.get("currency", "AED"),
                  "note": "Synthetic smoke-set document. Labels are known by construction."}
        for f in SCALARS:
            if f == "cancellation_clause":
                v = "present" if t["has_cancellation_clause"] else None
            else:
                v = t[f]
            labels[f] = {"value": v, "page": inp[f]["source_page"], "quote": inp[f]["source_quote"]}
        labels["payment_plan"] = [{**{k: m[k] for k in ("name", "percent", "due_date", "trigger")},
                                   "page": r["source_page"], "quote": r["source_quote"]}
                                  for m, r in zip(t["payment_plan"], inp["payment_plan"])]
        (out / "labels.json").write_text(json.dumps(labels, indent=2))
        print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
